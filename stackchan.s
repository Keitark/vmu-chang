.org $0480
start:
    clr1 IE, 7
    mov #$80, SP
    mov #$a1, OCR
    mov #$09, MCR
    mov #$80, VCCR
    mov #$ff, P3
    clr1 P3INT, 0
    clr1 P3INT, 1
    clr1 P1, 7
    mov #0, XBNK
    mov #0, PHASE
    mov #0, TTL
    mov #0, FRAME
    mov #$3F, KEYLAST
    set1 IE, 7
main_loop:
    callf keys
    callf choose_frame
    callf present
    callf wait_frame
    inc PHASE
    ld TTL
    bz next_frame
    dec TTL
next_frame:
    jmpf main_loop

; Hardware input: Port 3 bits 0-5 active-low:
; 0 UP,1 DOWN,2 LEFT,3 RIGHT,4 A,5 B.
keys:
    bp P7,0,keys_quit
    ld P3
    bn ACC,6,keys_quit
    bn ACC,7,keys_sleep
    and #$3f
    st KEYCUR
    ld KEYLAST
    be KEYCUR,keys_ret
    ld KEYCUR
    st KEYLAST
    be #$3f,keys_ret
    bn ACC,4,keys_a
    bn ACC,5,keys_b
    bn ACC,0,keys_up
    bn ACC,1,keys_down
    bn ACC,2,keys_left
    bn ACC,3,keys_right
keys_ret:
    ret
keys_a:
    mov #8, BASE
    jmpf reaction
keys_b:
    mov #12, BASE
    jmpf reaction
keys_up:
    mov #16, BASE
    jmpf reaction
keys_down:
    mov #20, BASE
    jmpf reaction
keys_left:
    mov #24, BASE
    jmpf reaction
keys_right:
    mov #28, BASE
    jmpf reaction
reaction:
    mov #16, TTL
    mov #0, PHASE
    ret
keys_quit:
    jmpf goodbye
keys_sleep:
    bn P3,7,keys_sleep
    mov #0, VCCR
sleep_more:
    set1 PCON,0
    bp P7,0,keys_quit
    bp P3,7,sleep_more
    mov #$80,VCCR
sleep_release:
    bn P3,7,sleep_release
    ret

choose_frame:
    ld TTL
    bz choose_idle
    ld PHASE
    and #$03
    add BASE
    st FRAME
    ret
choose_idle:
    ld PHASE
    and #$1f
    st PHASE
    be #10,choose_half
    be #11,choose_blink
    be #12,choose_half
    be #15,choose_tilt
    be #19,choose_left
    be #20,choose_left
    be #25,choose_right
    be #26,choose_right
    be #30,choose_smile
    and #1
    st FRAME
    ret
choose_tilt:
    mov #7,FRAME
    ret
choose_half:
    mov #2,FRAME
    ret
choose_blink:
    mov #3,FRAME
    ret
choose_left:
    mov #4,FRAME
    ret
choose_right:
    mov #5,FRAME
    ret
choose_smile:
    mov #6,FRAME
    ret

; Frame pointers are 16-bit little endian, 32 sprites x 192 bytes.
; Fetch an indexed pointer using the VMU Table Reference registers, then
; paint the chosen full-screen mono sprite to both LCD XRAM banks.
present:
    mov #<frame_table, TRL
    mov #>frame_table, TRH
    ld FRAME
    add FRAME
    st INDEX
    ld INDEX
    ldc
    st PTRLO
    inc INDEX
    ld INDEX
    ldc
    st TRH
    ld PTRLO
    st TRL
    callf paint
    ret

paint:
    clr1 OCR,5
    push ACC
    push XBNK
    push C
    push 2
    mov #$80, 2
    mov #0, XBNK
    mov #0, C
    ld C               ; REQUIRED: first LDC offset must be zero
paint_loop:
    ldc
    st @R2
    inc 2
    ld 2
    and #$0f
    bne #$0c,paint_no_gap
    ld 2
    add #4
    st 2
    bnz paint_no_gap
    inc XBNK
    mov #$80, 2
paint_no_gap:
    inc C
    ld C
    bne #$c0,paint_loop
    pop 2
    pop C
    pop XBNK
    pop ACC
    set1 OCR,5
    ret

wait_frame:
    push B
    push C
    mov #12,B
wait_outer:
    mov #0,C
wait_inner:
    dbnz C,wait_inner
    dbnz B,wait_outer
    pop C
    pop B
    ret

